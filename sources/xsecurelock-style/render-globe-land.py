#!/usr/bin/env python3
"""Generate skynet-globe-land.h: a run-length coded equirectangular land mask.

Source: Natural Earth 1:50m land polygons (public domain),
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_land.geojson

Usage: python3 -I render-globe-land.py ne_50m_land.geojson skynet-globe-land.h
The header is committed; this script only runs again when the map changes.
"""
import json
import sys

from PIL import Image, ImageDraw

W, H = 1024, 512          # stored mask: 0.35 degrees per pixel
SS = 4                    # rasterise at 4x, then box-filter down


def rings(geometry):
    if geometry['type'] == 'Polygon':
        yield from geometry['coordinates']
    elif geometry['type'] == 'MultiPolygon':
        for polygon in geometry['coordinates']:
            yield from polygon


def main(src, out):
    data = json.load(open(src, encoding='utf-8'))
    big = Image.new('L', (W * SS, H * SS), 0)
    draw = ImageDraw.Draw(big)
    for feature in data['features']:
        for index, ring in enumerate(rings(feature['geometry'])):
            points = [((lon + 180) / 360 * W * SS, (90 - lat) / 180 * H * SS)
                      for lon, lat in ring]
            if len(points) >= 3:
                # Outer rings are land; Natural Earth land holes are lakes/seas.
                draw.polygon(points, fill=255 if index == 0 else 0)
    mask = big.resize((W, H), Image.BOX).point(lambda v: 255 if v >= 128 else 0)
    px = mask.load()
    runs = []
    for y in range(H):
        value, length = 0, 0
        for x in range(W):
            cell = 1 if px[x, y] else 0
            if cell == value:
                length += 1
            else:
                runs.append(length)
                value, length = cell, 1
        runs.append(length)
        runs.append(0xFFFF)          # row terminator
    lines = []
    for i in range(0, len(runs), 16):
        lines.append('  ' + ','.join(str(v) for v in runs[i:i + 16]) + ',')
    with open(out, 'w', encoding='ascii') as fh:
        fh.write('/* Generated by render-globe-land.py from Natural Earth 1:50m land\n'
                 ' * (public domain). Equirectangular, west->east from 180W, rows from 90N.\n'
                 ' * Each row: alternating sea/land run lengths, terminated by 0xFFFF. */\n'
                 '#ifndef SKYNET_GLOBE_LAND_H\n#define SKYNET_GLOBE_LAND_H\n'
                 f'#define SKYGLOBE_MAP_W {W}\n#define SKYGLOBE_MAP_H {H}\n'
                 'static const unsigned short skyglobe_land_runs[] = {\n')
        fh.write('\n'.join(lines))
        fh.write('\n};\n#endif\n')
    print(f'{len(runs)} runs')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
